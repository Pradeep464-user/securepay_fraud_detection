const express = require('express');
const router = express.Router();
const User = require('../models/User');
const Transaction = require('../models/Transaction');
const FraudAlert = require('../models/FraudAlert');
const authenticateToken = require('../middleware/authMiddleware');
const { analyzeTransactionRisk } = require('../services/fraudDetection');

// Helper to generate transaction ID: SP-TX-TIMESTAMP-RANDOM
const generateTxId = () => {
  const ts = Date.now().toString(36).toUpperCase();
  const rand = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `TX-${ts}-${rand}`;
};

// Helper to generate alert ID: FA-TIMESTAMP-RANDOM
const generateAlertId = () => {
  const ts = Date.now().toString(36).toUpperCase();
  const rand = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `ALT-${ts}-${rand}`;
};

// POST /api/transactions/send
router.post('/send', authenticateToken, async (req, res) => {
  try {
    const { receiverIdentifier, amount, customHour } = req.body;
    const transferAmount = Number(amount);

    if (!receiverIdentifier || !transferAmount || transferAmount <= 0) {
      return res.status(400).json({
        success: false,
        message: 'Valid receiver (email or account number) and positive amount required.'
      });
    }

    const sender = await User.findById(req.user._id);
    if (!sender) {
      return res.status(404).json({ success: false, message: 'Sender not found.' });
    }

    // Find receiver by email or account number
    const trimmedIdentifier = receiverIdentifier.trim();
    const receiver = await User.findOne({
      $or: [
        { email: trimmedIdentifier.toLowerCase() },
        { accountNumber: trimmedIdentifier.toUpperCase() }
      ]
    });

    if (!receiver) {
      return res.status(404).json({
        success: false,
        message: `Receiver "${receiverIdentifier}" not found. Please check the email or account number.`
      });
    }

    // Cannot send money to yourself
    if (sender._id.toString() === receiver._id.toString()) {
      return res.status(400).json({
        success: false,
        message: 'Cannot transfer funds to your own account.'
      });
    }

    // Balance check
    if (sender.balance < transferAmount) {
      return res.status(400).json({
        success: false,
        message: `Insufficient balance. Available: ₹${sender.balance.toLocaleString('en-IN')}, Requested: ₹${transferAmount.toLocaleString('en-IN')}`
      });
    }

    // Execute Rule-Based Fraud Analysis
    const riskAnalysis = await analyzeTransactionRisk({
      senderId: sender._id,
      amount: transferAmount,
      txTimestamp: new Date(),
      customHour: typeof customHour === 'number' ? customHour : null
    });

    const txId = generateTxId();

    const transaction = new Transaction({
      transactionId: txId,
      sender: sender._id,
      receiver: receiver._id,
      senderEmail: sender.email,
      receiverEmail: receiver.email,
      amount: transferAmount,
      type: 'transfer',
      status: riskAnalysis.status,
      riskScore: riskAnalysis.riskScore,
      riskLevel: riskAnalysis.riskLevel,
      breakdown: {
        amountScore: riskAnalysis.amountScore,
        frequencyScore: riskAnalysis.frequencyScore,
        timingScore: riskAnalysis.timingScore,
        reasons: riskAnalysis.reasons,
        historicalAverage: riskAnalysis.historicalAverage,
        recentCount: riskAnalysis.recentCount,
        timingHour: riskAnalysis.timingHour
      }
    });

    await transaction.save();

    // Execute Balance Adjustments based on decision logic
    if (riskAnalysis.riskLevel === 'LOW') {
      // Completed: immediate settlement
      sender.balance -= transferAmount;
      receiver.balance += transferAmount;
      await sender.save();
      await receiver.save();
    } else if (riskAnalysis.riskLevel === 'MEDIUM') {
      // Monitored: settled but flagged
      sender.balance -= transferAmount;
      receiver.balance += transferAmount;
      await sender.save();
      await receiver.save();
    } else if (riskAnalysis.riskLevel === 'HIGH') {
      // High Risk: Hold funds in escrow pending analyst review
      // Sender's balance is debited so funds are reserved, receiver not credited yet.
      sender.balance -= transferAmount;
      await sender.save();

      // Automatically generate FraudAlert
      const alert = new FraudAlert({
        alertId: generateAlertId(),
        transaction: transaction._id,
        sender: sender._id,
        riskScore: riskAnalysis.riskScore,
        riskLevel: riskAnalysis.riskLevel,
        reasons: riskAnalysis.reasons,
        status: 'OPEN',
        notes: 'Automatically generated by SecurePay Rule-Based Fraud Engine'
      });
      await alert.save();
    }

    return res.status(201).json({
      success: true,
      message: riskAnalysis.riskLevel === 'HIGH'
        ? 'Transaction flagged as HIGH RISK and held for security review.'
        : riskAnalysis.riskLevel === 'MEDIUM'
        ? 'Transaction processed with active monitoring.'
        : 'Transaction completed successfully.',
      transaction,
      newBalance: sender.balance
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: 'Transaction processing failed',
      error: error.message
    });
  }
});

// GET /api/transactions/my-transactions
router.get('/my-transactions', authenticateToken, async (req, res) => {
  try {
    const transactions = await Transaction.find({
      $or: [{ sender: req.user._id }, { receiver: req.user._id }]
    })
      .sort({ createdAt: -1 })
      .populate('sender', 'name email accountNumber')
      .populate('receiver', 'name email accountNumber');

    return res.status(200).json({
      success: true,
      count: transactions.length,
      transactions
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: 'Failed to retrieve transactions',
      error: error.message
    });
  }
});

// GET /api/transactions/:id
router.get('/:id', authenticateToken, async (req, res) => {
  try {
    const transaction = await Transaction.findById(req.params.id)
      .populate('sender', 'name email accountNumber')
      .populate('receiver', 'name email accountNumber');

    if (!transaction) {
      return res.status(404).json({ success: false, message: 'Transaction not found' });
    }

    // Allow sender, receiver, or admin
    const isParty =
      transaction.sender._id.toString() === req.user._id.toString() ||
      transaction.receiver._id.toString() === req.user._id.toString() ||
      req.user.role === 'admin';

    if (!isParty) {
      return res.status(403).json({ success: false, message: 'Unauthorized to view this transaction' });
    }

    return res.status(200).json({
      success: true,
      transaction
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: 'Failed to retrieve transaction details',
      error: error.message
    });
  }
});

module.exports = router;
